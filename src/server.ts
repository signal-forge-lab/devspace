export function createServer(
  config = loadConfig(),
  options: CreateServerOptions = {},
): RunningServer {
  const incomingArtifactAdapters = options.incomingArtifactAdapters
    ?? [createOpenAIIncomingArtifactAdapter()];
  const allowedHosts = config.allowedHosts.includes("*")
    ? undefined
    : Array.from(new Set([config.host, ...config.allowedHosts]));
  const app = createMcpExpressApp({
    host: config.host,
    ...(allowedHosts ? { allowedHosts } : {}),
  });
  const sessionLifecycle = new McpSessionLifecycle<Transport>({
    log: (level, event, fields) => logEvent(config.logging, level, event, fields),
  });
  const mcpUrl = new URL("/mcp", config.publicBaseUrl);
  const resourceServerUrl = resourceUrlFromServerUrl(mcpUrl);
  const oauthProvider = new SingleUserOAuthProvider(config.oauth, mcpUrl, config.stateDir);
  const bearerAuth = requireBearerAuth({
    verifier: oauthProvider,
    requiredScopes: [config.oauth.scopes[0] ?? "devspace"],
    resourceMetadataUrl: getOAuthProtectedResourceMetadataUrl(resourceServerUrl),
  });
  const workspaceStore = createWorkspaceStore(config.stateDir, config.workspaceSessionMaxAgeMs);
  const workspaces = new WorkspaceRegistry(config, workspaceStore);
  const reviewCheckpoints = createReviewCheckpointManager();
  const processSessions = new ProcessSessionManager();
  const softPause = new SoftPauseController(config.stateDir);
  const sessionMonitor = new SessionMonitor();
  const serverStartedAt = Date.now();
  const localAgentProviders = config.subagents
    ? getLocalAgentProviderAvailabilitySnapshot()
    : [];
  sessionLifecycle.start();

  if (config.logging.trustProxy) {
    app.set("trust proxy", 1);
  }

  app.use((req, res, next) => {
    const requestId = randomUUID();
    const startedAt = performance.now();
    res.locals.requestId = requestId;

    res.on("finish", () => {
      const path = requestPath(req);
      if (!config.logging.requests) return;
      if (!config.logging.assets && path.startsWith("/mcp-app-assets")) return;

      logEvent(config.logging, "info", "http_request", {
        requestId,
        method: req.method,
        path,
        status: res.statusCode,
        classification: classifyHttpRequest(path, res.statusCode),
        durationMs: Math.round(performance.now() - startedAt),
        ...requestLogFields(req, config),
      });
    });

    next();
  });

  app.use(
    mcpAuthRouter({
      provider: oauthProvider,
      issuerUrl: new URL(config.publicBaseUrl),
      baseUrl: new URL(config.publicBaseUrl),
      resourceServerUrl,
      scopesSupported: config.oauth.scopes,
      resourceName: PRODUCT_DISPLAY_NAME,
    }),
  );

  app.get("/healthz", (_req, res) => {
    res.json({ ok: true, name: LEGACY_SERVICE_NAME });
  });

  const runtimeStatus = (): SessionMonitorRuntimeStatus => {
    const pauseState = softPause.status();
    const memory = process.memoryUsage();
    return {
      server: {
        status: "running",
        pid: process.pid,
        startedAt: new Date(serverStartedAt).toISOString(),
        uptimeMs: Math.max(0, Date.now() - serverStartedAt),
        version: PACKAGE_VERSION,
        port: config.port,
        controlEnabled: Boolean(process.env.WORKBRIDGE_MONITOR_CONTROL_TOKEN?.trim()),
        memory: {
          rssBytes: memory.rss,
          heapUsedBytes: memory.heapUsed,
        },
      },
      mcpSessions: sessionLifecycle.snapshot(8),
      ...(pauseState ? { softPause: pauseState } : {}),
    };
  };
  const sessionMonitorRoutes = registerSessionMonitorRoutes(
    app,
    sessionMonitor,
    undefined,
    runtimeStatus,
  );

  app.all("/mcp", async (req, res) => {
    const requestId = res.locals.requestId as string | undefined;
    const sessionId = req.header("mcp-session-id");
    const initializeRequest = req.method === "POST" && isInitializeRequest(req.body);
    const requestMethods = mcpRequestMethods(req.method, req.body);

    await new Promise<void>((resolve, reject) => {
      bearerAuth(req, res, (error?: unknown) => {
        if (error) reject(error);
        else resolve();
      });
    });
    if (res.headersSent) return;

    if (!req.auth?.resource || !checkResourceAllowed({ requestedResource: req.auth.resource, configuredResource: resourceServerUrl })) {
      logEvent(config.logging, "warn", "auth_denied", {
        requestId,
        method: req.method,
        path: requestPath(req),
        reason: "invalid_oauth_resource",
        ...requestLogFields(req, config),
      });
      sendJsonRpcError(res, 401, -32001, "Unauthorized");
      return;
    }

    logEvent(config.logging, "debug", "mcp_request", {
      requestId,
      method: req.method,
      requestMethods,
      sessionIdPresent: Boolean(sessionId),
      sessionIdPrefix: sessionIdPrefix(sessionId),
      isInitialize: initializeRequest,
    });

    try {
      let transport: Transport | undefined;

      if (sessionId) {
        transport = sessionLifecycle.beginRequest(sessionId, requestMethods);
        if (!transport) {
          sendJsonRpcError(res, 404, -32000, "Unknown MCP session");
          return;
        }
        sessionLifecycle.trackRequestUntilResponseEnd(sessionId, res);
      } else if (initializeRequest) {
        transport = new StreamableHTTPServerTransport({
          sessionIdGenerator: () => randomUUID(),
          onsessioninitialized: (newSessionId) => {
            const metadata = mcpInitializeMetadata(req);
            if (transport) {
              sessionLifecycle.register(newSessionId, transport, metadata, {
                requestActive: true,
                oneShotCleanupEligible: isOpenAiMcpClient(metadata),
              });
              sessionLifecycle.trackRequestUntilResponseEnd(newSessionId, res);
            }
            logEvent(config.logging, "info", "mcp_session_created", {
              requestId,
              sessionIdPrefix: sessionIdPrefix(newSessionId),
              activeSessionCount: sessionLifecycle.size,
              clientName: metadata.clientName,
              clientVersion: metadata.clientVersion,
              protocolVersion: metadata.protocolVersion,
              ...requestLogFields(req, config),
            });
          },
        });

        transport.onclose = () => {
          const closedSessionId = transport?.sessionId;
          if (closedSessionId) {
            sessionLifecycle.remove(closedSessionId, "transport_close");
          }
        };

        const server = createMcpServer(
          config,
          workspaces,
          reviewCheckpoints,
          processSessions,
          localAgentProviders,
          incomingArtifactAdapters,
          softPause,
          {
            monitor: sessionMonitor,
            sessionId: () => transport?.sessionId,
          },
        );
        await server.connect(transport);
      } else {
        sendJsonRpcError(res, 400, -32000, "No valid MCP session");
        return;
      }

      await transport.handleRequest(req, res, req.body);
    } catch (error) {
      logEvent(config.logging, "error", "mcp_request_error", {
        requestId,
        error: error instanceof Error ? error.message : String(error),
      });
      if (!res.headersSent) {
        sendJsonRpcError(res, 500, -32603, "Internal server error");
      }
    }
  });

  let closePromise: Promise<void> | undefined;
  return {
    app,
    config,
    localAgentProviders,
    close: () => {
      closePromise ??= (async () => {
        sessionMonitorRoutes.close();
        await sessionLifecycle.close();
        processSessions.shutdown();
        oauthProvider.close();
        workspaceStore.close?.();
      })();
      return closePromise;
    },
  };
}

function mcpRequestMethods(httpMethod: string, body: unknown): string[] {
  if (httpMethod !== "POST") return [`http/${httpMethod.toLowerCase()}`];
  const messages = Array.isArray(body) ? body : [body];
  return messages.flatMap((message) => {
    if (!message || typeof message !== "object") return [];
    const method = (message as { method?: unknown }).method;
    return typeof method === "string" && method ? [method] : [];
  });
}

function mcpInitializeMetadata(req: Request): {
  clientName?: string;
  clientVersion?: string;
  protocolVersion?: string;
  userAgent?: string;
} {
  const body = req.body;
  const message = Array.isArray(body) ? body.find((entry) => isInitializeRequest(entry)) : body;
  if (!message || typeof message !== "object") {
    return { userAgent: req.get("user-agent") };
  }
  const params = (message as { params?: unknown }).params;
  if (!params || typeof params !== "object") {
    return { userAgent: req.get("user-agent") };
  }
  const clientInfo = (params as { clientInfo?: unknown }).clientInfo;
  return {
    clientName: stringProperty(clientInfo, "name"),
    clientVersion: stringProperty(clientInfo, "version"),
    protocolVersion: stringProperty(params, "protocolVersion"),
    userAgent: req.get("user-agent"),
  };
}

function stringProperty(value: unknown, property: string): string | undefined {
  if (!value || typeof value !== "object") return undefined;
  const candidate = (value as Record<string, unknown>)[property];
  return typeof candidate === "string" && candidate.trim() ? candidate.trim().slice(0, 160) : undefined;
}

async function isMainModule(): Promise<boolean> {
  if (!process.argv[1]) return false;

  const modulePath = await realpath(fileURLToPath(import.meta.url));
  const entrypointPath = await realpath(process.argv[1]);
  return modulePath === entrypointPath;
}

if (await isMainModule()) {
  const { app, config, close, localAgentProviders } = createServer();
  const httpServer = app.listen(config.port, config.host, () => {
    console.log(
      `${PRODUCT_DISPLAY_NAME} listening on http://${config.host}:${config.port}/mcp`,
    );
    console.log(`session monitor: http://127.0.0.1:${config.port}/monitor`);
    console.log(`allowed roots: ${config.allowedRoots.join(", ")}`);
    console.log("auth: oauth owner-token flow required");
    console.log(`logging: ${config.logging.level} ${config.logging.format}`);
    console.log(`request logging: ${config.logging.requests ? "enabled" : "disabled"}`);
    console.log(`asset logging: ${config.logging.assets ? "enabled" : "disabled"}`);
    console.log(`trust proxy: ${config.logging.trustProxy ? "enabled" : "disabled"}`);
    console.log(
      `native artifact download: ${isArtifactDownloadSupportedPlatform() ? "enabled" : `unsupported on ${process.platform}`}`,
    );
    if (config.subagents) {
      console.log(`subagent providers: ${formatLocalAgentProviderAvailabilitySummary(localAgentProviders)}`);
    }
  });

  let shuttingDown = false;
  const shutdown = async () => {
    if (shuttingDown) return;
    shuttingDown = true;
    await shutdownHttpServer(httpServer, close);
    process.exit(0);
  };
  const handleShutdown = () => {
    void shutdown().catch((error) => {
      console.error("devspace shutdown failed", error);
      process.exit(1);
    });
  };
  process.once("SIGINT", handleShutdown);
  process.once("SIGTERM", handleShutdown);
}
